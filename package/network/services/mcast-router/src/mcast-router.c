/*
 * mcast-router: relays link-local multicast discovery between networks by
 * policy. Each protocol (proto-mdns.c, proto-ssdp.c, ...) is a separate
 * source file describing itself with a struct mcr_plugin; all are built in
 * and listed in builtin[] below.
 *
 * Link-local multicast (mDNS 224.0.0.251/ff02::fb, SSDP 239.255.255.250/
 * ff02::c) never crosses a router. This daemon joins each protocol's group
 * on a list of interfaces, knows which interface (and so which client) every
 * packet came from, and re-sends it from the router's own address on the
 * interfaces the policy allows:
 *
 *   query from B          -> networks of every A that B may discover
 *   answer/announce from A -> networks of every B that may discover A
 *
 * "B may discover A" is an 'allow <proto> B A' or an 'out <proto> A' line
 * in the configuration (generated by the access tool). In permissive mode a
 * relay between two clients that are not enforced is done even when the
 * policy does not allow it, and recorded as "would be denied"; relays
 * involving an enforced client follow the policy and denials are recorded.
 *
 * Queries whose answers come back unicast (SSDP M-SEARCH, legacy mDNS) are
 * sent from a reply-proxy socket; replies to it are passed back to the
 * original sender.
 *
 * Configuration (default /etc/mcast-router.conf), one directive per line:
 *   mode permissive|enforce
 *   protocol <name>                   enable a built-in protocol (mdns, ssdp)
 *   proxy_ports <first> <last>        UDP ports for reply proxies
 *   ratelimit <packets per second>    per interface and protocol
 *   iface <ifname> <client> [enforce]
 *   allow <proto|*> <seeker> <provider>
 *   out <proto|*> <provider>
 *
 * Records: <statedir>/records (TSV: status proto kind from to count first
 * last desc) and <statedir>/stats, written every 30 s, on SIGUSR1 and on
 * exit. SIGHUP reloads the configuration.
 *
 * SPDX-License-Identifier: GPL-2.0-only
 */
