static int proxy_first = 41900, proxy_last = 41999, proxy_cursor;
static double ratelimit = 100;

static struct plugin plugins[MAX_PLUGINS];
static int nplugins;
static struct iface ifaces[MAX_IFACES];
static int nifaces;
static struct rule *rules;
static int nrules, cap_rules;
static struct proxy proxies[MAX_PROXIES];
static struct record records[MAX_RECORDS];
static struct local_addr locals[MAX_LOCAL];
static int nlocals;

static volatile sig_atomic_t sig_reload, sig_dump, sig_stop;

static void logmsg(int prio, const char *fmt, ...)
{
	va_list ap;

	if (prio == LOG_DEBUG && !verbose)
		return;
	va_start(ap, fmt);
	if (foreground) {
		vfprintf(stderr, fmt, ap);
		fputc('\n', stderr);
	} else {
		vsyslog(prio, fmt, ap);
	}
	va_end(ap);
}

static const char *kind_name(int kind)
{
	return kind == MCR_QUERY ? "query" : kind == MCR_ANSWER ? "answer" : "ignore";
}

/* ---------- configuration ---------- */

static void add_rule(const char *proto, const char *seeker, const char *provider)
{
	if (nrules == cap_rules) {
		int n = cap_rules ? cap_rules * 2 : 64;
		struct rule *r = realloc(rules, n * sizeof(*r));
		if (!r)
			return;
		rules = r;
		cap_rules = n;
	}
	snprintf(rules[nrules].proto, sizeof(rules[nrules].proto), "%s", proto);
	snprintf(rules[nrules].seeker, ID_LEN, "%s", seeker);
	snprintf(rules[nrules].provider, ID_LEN, "%s", provider);
	nrules++;
}

static int enable_protocol(const char *name)
{
	const struct mcr_plugin *p = NULL;
	struct plugin *pl;

	for (int i = 0; builtin[i]; i++)
		if (!strcmp(builtin[i]->name, name))
			p = builtin[i];
	if (!p) {
		logmsg(LOG_ERR, "unknown protocol '%s'", name);
		return -1;
	}
	if (nplugins == MAX_PLUGINS)
		return -1;
	pl = &plugins[nplugins];
	memset(pl, 0, sizeof(*pl));
	pl->p = p;
	pl->fd4 = pl->fd6 = -1;
	pl->has4 = p->group4 && inet_pton(AF_INET, p->group4, &pl->grp4) == 1;
	pl->has6 = p->group6 && inet_pton(AF_INET6, p->group6, &pl->grp6) == 1;
	nplugins++;
	logmsg(LOG_INFO, "protocol %s: port %u, groups %s %s", p->name, p->port,
	       pl->has4 ? p->group4 : "-", pl->has6 ? p->group6 : "-");
	return 0;
}

static int plugin_by_name(const char *name)
{
	for (int i = 0; i < nplugins; i++)
		if (!strcmp(plugins[i].p->name, name))
			return i;
	return -1;
}

static int read_config(void)
{
	FILE *f = fopen(conf_path, "r");
	char line[512];
	int lineno = 0;

	if (!f) {
		logmsg(LOG_ERR, "%s: %s", conf_path, strerror(errno));
		return -1;
	}
	while (fgets(line, sizeof(line), f)) {
		char *tok[5] = { 0 };
		int n = 0;
		char *save, *t;

		lineno++;
		if ((t = strchr(line, '#')))
			*t = 0;
		for (t = strtok_r(line, " \t\r\n", &save); t && n < 5; t = strtok_r(NULL, " \t\r\n", &save))
			tok[n++] = t;
		if (!n)
			continue;

		if (!strcmp(tok[0], "mode") && n == 2) {
			permissive = !strcmp(tok[1], "permissive");
		} else if (!strcmp(tok[0], "protocol") && n == 2) {
			if (plugin_by_name(tok[1]) < 0)
				enable_protocol(tok[1]);
		} else if (!strcmp(tok[0], "proxy_ports") && n == 3) {
			proxy_first = atoi(tok[1]);
			proxy_last = atoi(tok[2]);
		} else if (!strcmp(tok[0], "ratelimit") && n == 2) {
			ratelimit = atof(tok[1]);
		} else if (!strcmp(tok[0], "iface") && (n == 3 || n == 4)) {
			struct iface *ifc;

			if (nifaces == MAX_IFACES) {
				logmsg(LOG_ERR, "%s:%d: too many interfaces", conf_path, lineno);
				continue;
			}
			ifc = &ifaces[nifaces++];
			memset(ifc, 0, sizeof(*ifc));
			snprintf(ifc->name, sizeof(ifc->name), "%s", tok[1]);
			snprintf(ifc->id, sizeof(ifc->id), "%s", tok[2]);
			ifc->enforce = n == 4 && !strcmp(tok[3], "enforce");
		} else if (!strcmp(tok[0], "allow") && n == 4) {
			add_rule(tok[1], tok[2], tok[3]);
		} else if (!strcmp(tok[0], "out") && n == 3) {
			add_rule(tok[1], "*", tok[2]);
		} else {
			logmsg(LOG_WARNING, "%s:%d: ignored", conf_path, lineno);
		}
	}
	fclose(f);
	if (proxy_first < 1024 || proxy_last < proxy_first || proxy_last > 65535) {
		logmsg(LOG_WARNING, "bad proxy_ports, using 41900-41999");
		proxy_first = 41900;
		proxy_last = 41999;
	}
	proxy_cursor = proxy_first;
	logmsg(LOG_INFO, "configuration: %s mode, %d protocol(s), %d interface(s), %d rule(s)",
	       permissive ? "permissive" : "enforce", nplugins, nifaces, nrules);
	return 0;
}

/* B (seeker) may discover A (provider) with this protocol */
static int may_discover(int pi, const char *seeker, const char *provider)
{
	const char *name = plugins[pi].p->name;

	for (int i = 0; i < nrules; i++) {
		struct rule *r = &rules[i];
		if (strcmp(r->proto, "*") && strcmp(r->proto, name))
			continue;
		if (strcmp(r->provider, provider))
			continue;
		if (!strcmp(r->seeker, "*") || !strcmp(r->seeker, seeker))
			return 1;
	}
	return 0;
}

/* ---------- local addresses (loop protection) ---------- */

static void refresh_locals(void)
{
	struct ifaddrs *ifa, *i;

	nlocals = 0;
	if (getifaddrs(&ifa))
		return;
	for (i = ifa; i && nlocals < MAX_LOCAL; i = i->ifa_next) {
		if (!i->ifa_addr)
			continue;
		if (i->ifa_addr->sa_family == AF_INET) {
			locals[nlocals].family = AF_INET;
			locals[nlocals++].u.a4 = ((struct sockaddr_in *)i->ifa_addr)->sin_addr;
		} else if (i->ifa_addr->sa_family == AF_INET6) {
			locals[nlocals].family = AF_INET6;
			locals[nlocals++].u.a6 = ((struct sockaddr_in6 *)i->ifa_addr)->sin6_addr;
		}
	}
	freeifaddrs(ifa);
}

static int is_local(const struct sockaddr_storage *ss)
{
	for (int i = 0; i < nlocals; i++) {
		if (ss->ss_family == AF_INET && locals[i].family == AF_INET &&
		    ((const struct sockaddr_in *)ss)->sin_addr.s_addr == locals[i].u.a4.s_addr)
			return 1;
		if (ss->ss_family == AF_INET6 && locals[i].family == AF_INET6 &&
		    !memcmp(&((const struct sockaddr_in6 *)ss)->sin6_addr, &locals[i].u.a6, sizeof(struct in6_addr)))
			return 1;
	}
	return 0;
}

/* ---------- sockets ---------- */

static int open_socket(int family, uint16_t port, int ttl)
{
	int fd = socket(family, SOCK_DGRAM | SOCK_NONBLOCK | SOCK_CLOEXEC, 0);
	int one = 1, zero = 0;

	if (fd < 0)
		return -1;
	setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
	if (family == AF_INET) {
		struct sockaddr_in sa = { .sin_family = AF_INET, .sin_port = htons(port) };
		unsigned char t = ttl, loop = 0;

		setsockopt(fd, IPPROTO_IP, IP_PKTINFO, &one, sizeof(one));
		setsockopt(fd, IPPROTO_IP, IP_MULTICAST_ALL, &zero, sizeof(zero));
		setsockopt(fd, IPPROTO_IP, IP_MULTICAST_LOOP, &loop, sizeof(loop));
		setsockopt(fd, IPPROTO_IP, IP_MULTICAST_TTL, &t, sizeof(t));
		if (bind(fd, (struct sockaddr *)&sa, sizeof(sa)) < 0)
			goto fail;
	} else {
		struct sockaddr_in6 sa = { .sin6_family = AF_INET6, .sin6_port = htons(port) };

		setsockopt(fd, IPPROTO_IPV6, IPV6_V6ONLY, &one, sizeof(one));
		setsockopt(fd, IPPROTO_IPV6, IPV6_RECVPKTINFO, &one, sizeof(one));
		setsockopt(fd, IPPROTO_IPV6, IPV6_MULTICAST_ALL, &zero, sizeof(zero));
		setsockopt(fd, IPPROTO_IPV6, IPV6_MULTICAST_LOOP, &zero, sizeof(zero));
		setsockopt(fd, IPPROTO_IPV6, IPV6_MULTICAST_HOPS, &ttl, sizeof(ttl));
		setsockopt(fd, IPPROTO_IPV6, IPV6_UNICAST_HOPS, &ttl, sizeof(ttl));
		if (bind(fd, (struct sockaddr *)&sa, sizeof(sa)) < 0)
			goto fail;
	}
	return fd;
fail:
	close(fd);
	return -1;
}

static void close_proxy(struct proxy *px)
{
	if (px->fd >= 0)
		close(px->fd);
	px->fd = -1;
}

static void close_all(void)
{
	for (int i = 0; i < nplugins; i++) {
		if (plugins[i].fd4 >= 0)
			close(plugins[i].fd4);
		if (plugins[i].fd6 >= 0)
			close(plugins[i].fd6);
		plugins[i].fd4 = plugins[i].fd6 = -1;
	}
	for (int i = 0; i < MAX_PROXIES; i++)
		close_proxy(&proxies[i]);
}

static void open_all(void)
{
	for (int i = 0; i < nplugins; i++) {
		struct plugin *pl = &plugins[i];

		if (pl->has4 && (pl->fd4 = open_socket(AF_INET, pl->p->port, pl->p->ttl)) < 0)
			logmsg(LOG_ERR, "%s: IPv4 port %u: %s", pl->p->name, pl->p->port, strerror(errno));
		if (pl->has6 && (pl->fd6 = open_socket(AF_INET6, pl->p->port, pl->p->ttl)) < 0)
			logmsg(LOG_ERR, "%s: IPv6 port %u: %s", pl->p->name, pl->p->port, strerror(errno));
	}
}

static int iface_addr4(const char *name, struct in_addr *a)
{
	struct ifreq ifr;
	int fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0), ok;

	if (fd < 0)
		return 0;
	memset(&ifr, 0, sizeof(ifr));
	snprintf(ifr.ifr_name, sizeof(ifr.ifr_name), "%.*s", IFNAMSIZ - 1, name);
	ok = ioctl(fd, SIOCGIFADDR, &ifr) == 0;
	if (ok)
		*a = ((struct sockaddr_in *)&ifr.ifr_addr)->sin_addr;
	close(fd);
	return ok;
}

/* find interfaces that appeared or changed, (re)join the groups on them */
static void scan_ifaces(void)
{
	for (int i = 0; i < nifaces; i++) {
		struct iface *ifc = &ifaces[i];
		int idx = if_nametoindex(ifc->name);

		ifc->ifindex = idx;
		ifc->has4 = idx && iface_addr4(ifc->name, &ifc->addr4);
		if (!idx)
			continue;
		for (int p = 0; p < nplugins; p++) {
			struct plugin *pl = &plugins[p];

			if (pl->fd4 >= 0 && ifc->joined4[p] != idx) {
				struct ip_mreqn m = { .imr_multiaddr = pl->grp4, .imr_ifindex = idx };

				if (setsockopt(pl->fd4, IPPROTO_IP, IP_ADD_MEMBERSHIP, &m, sizeof(m)) == 0 || errno == EADDRINUSE) {
					ifc->joined4[p] = idx;
					logmsg(LOG_DEBUG, "%s: joined %s on %s", pl->p->name, pl->p->group4, ifc->name);
				}
			}
			if (pl->fd6 >= 0 && ifc->joined6[p] != idx) {
				struct ipv6_mreq m = { .ipv6mr_multiaddr = pl->grp6, .ipv6mr_interface = idx };

				if (setsockopt(pl->fd6, IPPROTO_IPV6, IPV6_JOIN_GROUP, &m, sizeof(m)) == 0 || errno == EADDRINUSE) {
					ifc->joined6[p] = idx;
					logmsg(LOG_DEBUG, "%s: joined %s on %s", pl->p->name, pl->p->group6, ifc->name);
				}
			}
		}
	}
}

static struct iface *iface_by_index(int idx, int *pos)
{
	for (int i = 0; i < nifaces; i++)
		if (ifaces[i].ifindex == idx) {
			if (pos)
				*pos = i;
			return &ifaces[i];
		}
	return NULL;
}

/* ---------- records ---------- */

static void record(int denied, const struct mcr_plugin *proto, int kind, const char *from, const char *to, const char *desc)
{
	struct record *free_slot = NULL, *oldest = NULL;
	time_t now = time(NULL);

	for (int i = 0; i < MAX_RECORDS; i++) {
		struct record *r = &records[i];

		if (!r->used) {
			if (!free_slot)
				free_slot = r;
			continue;
		}
		if (r->denied == denied && r->proto == proto && r->kind == kind &&
		    !strcmp(r->from, from) && !strcmp(r->to, to)) {
			r->count++;
			r->last = now;
			if (desc[0])
				snprintf(r->desc, sizeof(r->desc), "%s", desc);
			return;
		}
		if (!oldest || r->last < oldest->last)
			oldest = r;
	}
	if (!free_slot)
		free_slot = oldest;
	memset(free_slot, 0, sizeof(*free_slot));
	free_slot->used = 1;
	free_slot->denied = denied;
	free_slot->proto = proto;
	free_slot->kind = kind;
	snprintf(free_slot->from, ID_LEN, "%s", from);
	snprintf(free_slot->to, ID_LEN, "%s", to);
	snprintf(free_slot->desc, sizeof(free_slot->desc), "%s", desc);
	free_slot->count = 1;
	free_slot->first = free_slot->last = now;
}

static void write_file(const char *name, void (*fill)(FILE *))
{
	char tmp[520], path[512];
	FILE *f;

	snprintf(path, sizeof(path), "%s/%s", state_dir, name);
	snprintf(tmp, sizeof(tmp), "%s.tmp", path);
	if (!(f = fopen(tmp, "w")))
		return;
	fill(f);
	if (fclose(f) == 0)
		rename(tmp, path);
}

static void fill_records(FILE *f)
{
	fprintf(f, "# status\tproto\tkind\tfrom\tto\tcount\tfirst\tlast\tdesc\n");
	for (int i = 0; i < MAX_RECORDS; i++) {
		struct record *r = &records[i];

		if (!r->used)
			continue;
		fprintf(f, "%s\t%s\t%s\t%s\t%s\t%lu\t%ld\t%ld\t%s\n", r->denied ? "denied" : "would",
			r->proto->name, kind_name(r->kind),
			r->from, r->to, r->count, (long)r->first, (long)r->last, r->desc);
	}
}

static void fill_stats(FILE *f)
{
	fprintf(f, "# mode %s\n# iface\tclient\tproto\trx\trelayed\tdenied\tlimited\n", permissive ? "permissive" : "enforce");
	for (int i = 0; i < nifaces; i++)
		for (int p = 0; p < nplugins; p++)
			fprintf(f, "%s\t%s\t%s\t%lu\t%lu\t%lu\t%lu\n", ifaces[i].name, ifaces[i].id, plugins[p].p->name,
				ifaces[i].rx[p], ifaces[i].relayed[p], ifaces[i].denied[p], ifaces[i].limited[p]);
}

static void dump(void)
{
	mkdir(state_dir, 0755);
	write_file("records", fill_records);
	write_file("stats", fill_stats);
}

/* ---------- sending ---------- */

static int send_on(int fd, int family, int ifindex, const struct in_addr *src4,
		   const struct sockaddr *dst, socklen_t dlen, const void *buf, size_t len)
{
	union {
		char b4[CMSG_SPACE(sizeof(struct in_pktinfo))];
		char b6[CMSG_SPACE(sizeof(struct in6_pktinfo))];
	} cbuf;
	struct iovec iov = { .iov_base = (void *)buf, .iov_len = len };
	struct msghdr msg = {
		.msg_name = (void *)dst, .msg_namelen = dlen,
		.msg_iov = &iov, .msg_iovlen = 1,
		.msg_control = &cbuf, .msg_controllen = sizeof(cbuf),
	};
	struct cmsghdr *c;

	memset(&cbuf, 0, sizeof(cbuf));
	c = CMSG_FIRSTHDR(&msg);
	if (family == AF_INET) {
		struct in_pktinfo pi = { .ipi_ifindex = ifindex };

		if (src4)
			pi.ipi_spec_dst = *src4;
		c->cmsg_level = IPPROTO_IP;
		c->cmsg_type = IP_PKTINFO;
		c->cmsg_len = CMSG_LEN(sizeof(pi));
		memcpy(CMSG_DATA(c), &pi, sizeof(pi));
		msg.msg_controllen = CMSG_SPACE(sizeof(pi));
	} else {
		struct in6_pktinfo pi = { .ipi6_ifindex = ifindex };

		c->cmsg_level = IPPROTO_IPV6;
		c->cmsg_type = IPV6_PKTINFO;
		c->cmsg_len = CMSG_LEN(sizeof(pi));
		memcpy(CMSG_DATA(c), &pi, sizeof(pi));
		msg.msg_controllen = CMSG_SPACE(sizeof(pi));
	}
	return sendmsg(fd, &msg, 0) < 0 ? -1 : 0;
}

static int send_group(struct plugin *pl, int fd, int family, struct iface *ifc, const void *buf, size_t len)
{
	if (family == AF_INET) {
		struct sockaddr_in d = { .sin_family = AF_INET, .sin_port = htons(pl->p->port), .sin_addr = pl->grp4 };

		if (!ifc->has4)
			return -1;      /* no IPv4 address there to send from */
		return send_on(fd, AF_INET, ifc->ifindex, &ifc->addr4, (struct sockaddr *)&d, sizeof(d), buf, len);
	} else {
		struct sockaddr_in6 d = { .sin6_family = AF_INET6, .sin6_port = htons(pl->p->port),
					  .sin6_addr = pl->grp6, .sin6_scope_id = ifc->ifindex };

		return send_on(fd, AF_INET6, ifc->ifindex, NULL, (struct sockaddr *)&d, sizeof(d), buf, len);
	}
}

static int same_sockaddr(const struct sockaddr_storage *a, const struct sockaddr_storage *b)
{
	if (a->ss_family != b->ss_family)
		return 0;
	if (a->ss_family == AF_INET) {
		const struct sockaddr_in *x = (const void *)a, *y = (const void *)b;
		return x->sin_addr.s_addr == y->sin_addr.s_addr && x->sin_port == y->sin_port;
	} else {
		const struct sockaddr_in6 *x = (const void *)a, *y = (const void *)b;
		return !memcmp(&x->sin6_addr, &y->sin6_addr, sizeof(x->sin6_addr)) && x->sin6_port == y->sin6_port;
	}
}

/* a reply proxy for this sender: reuse a live one or open a new socket */
static struct proxy *get_proxy(int pi, int family, const struct sockaddr_storage *seeker, socklen_t slen,
			       int seeker_if, int timeout)
{
	time_t now = time(NULL);
	struct proxy *px = NULL;
	int span = proxy_last - proxy_first + 1;

	for (int i = 0; i < MAX_PROXIES; i++)
		if (proxies[i].fd >= 0 && proxies[i].plugin == pi && proxies[i].family == family &&
		    same_sockaddr(&proxies[i].seeker, seeker)) {
			proxies[i].expires = now + timeout;
			return &proxies[i];
		}
	for (int i = 0; i < MAX_PROXIES && !px; i++)
		if (proxies[i].fd < 0)
			px = &proxies[i];
	if (!px)
		return NULL;
	for (int tries = 0; tries < span; tries++) {
		int port = proxy_cursor;
		int fd;

		proxy_cursor = proxy_cursor >= proxy_last ? proxy_first : proxy_cursor + 1;
		fd = open_socket(family, port, plugins[pi].p->ttl);
		if (fd < 0)
			continue;
		memset(px, 0, sizeof(*px));
		px->fd = fd;
		px->plugin = pi;
		px->family = family;
		memcpy(&px->seeker, seeker, slen);
		px->seeker_len = slen;
		px->seeker_if = seeker_if;
		px->expires = now + timeout;
		px->port = port;
		return px;
	}
	return NULL;
}

/* ---------- receiving ---------- */

static ssize_t recv_pkt(int fd, struct mcr_pkt *p, uint8_t *buf, int *ifindex)
{
	char cbuf[256];
	struct iovec iov = { .iov_base = buf, .iov_len = BUF_LEN };
	struct msghdr msg = {
		.msg_name = &p->src, .msg_namelen = sizeof(p->src),
		.msg_iov = &iov, .msg_iovlen = 1,
		.msg_control = cbuf, .msg_controllen = sizeof(cbuf),
	};
	ssize_t n;

	memset(p, 0, sizeof(*p));
	n = recvmsg(fd, &msg, 0);
	if (n < 0)
		return -1;
	if (msg.msg_flags & MSG_TRUNC)
		return -1;
	*ifindex = 0;
	for (struct cmsghdr *c = CMSG_FIRSTHDR(&msg); c; c = CMSG_NXTHDR(&msg, c)) {
		if (c->cmsg_level == IPPROTO_IP && c->cmsg_type == IP_PKTINFO) {
			struct in_pktinfo pi;

			memcpy(&pi, CMSG_DATA(c), sizeof(pi));
			*ifindex = pi.ipi_ifindex;
			p->multicast = IN_MULTICAST(ntohl(pi.ipi_addr.s_addr));
		} else if (c->cmsg_level == IPPROTO_IPV6 && c->cmsg_type == IPV6_PKTINFO) {
			struct in6_pktinfo pi;

			memcpy(&pi, CMSG_DATA(c), sizeof(pi));
			*ifindex = pi.ipi6_ifindex;
			p->multicast = IN6_IS_ADDR_MULTICAST(&pi.ipi6_addr);
		}
	}
	p->data = buf;
	p->len = n;
	p->cap = BUF_LEN;
	p->family = p->src.ss_family;
	p->src_port = p->family == AF_INET ? ntohs(((struct sockaddr_in *)&p->src)->sin_port)
					   : ntohs(((struct sockaddr_in6 *)&p->src)->sin6_port);
	p->proxy_timeout = 5;
	return n;
}

static void handle_group(int pi, int fd)
{
	static uint8_t buf[BUF_LEN];
	struct plugin *pl = &plugins[pi];
	struct mcr_pkt p;
	struct iface *from;
	struct proxy *px = NULL;
	int ifindex, from_pos = 0, kind;

	if (recv_pkt(fd, &p, buf, &ifindex) < 0)
		return;
	from = iface_by_index(ifindex, &from_pos);
	if (!from || is_local(&p.src))
		return;
	from->rx[pi]++;
	if (from->tokens[pi] < 1) {
		from->limited[pi]++;
		return;
	}
	from->tokens[pi] -= 1;

	kind = pl->p->classify(&p);
	if (kind == MCR_IGNORE)
		return;

	for (int t = 0; t < nifaces; t++) {
		struct iface *to = &ifaces[t];
		const char *seeker, *provider;
		int ok, out_fd = fd;

		if (t == from_pos || !to->ifindex || !strcmp(to->id, from->id))
			continue;
		if (p.family == AF_INET && !to->has4)
			continue;
		seeker = kind == MCR_QUERY ? from->id : to->id;
		provider = kind == MCR_QUERY ? to->id : from->id;
		ok = may_discover(pi, seeker, provider);
		if (!ok) {
			int both_permissive = permissive && !from->enforce && !to->enforce;

			record(!both_permissive, pl->p, kind, from->id, to->id, p.desc);
			if (!both_permissive) {
				from->denied[pi]++;
				logmsg(LOG_DEBUG, "%s %s %s -> %s denied (%s)", pl->p->name, kind_name(kind), from->id, to->id, p.desc);
				continue;
			}
		}
		if (kind == MCR_QUERY && p.need_proxy) {
			if (!px)
				px = get_proxy(pi, p.family, &p.src, p.family == AF_INET ? sizeof(struct sockaddr_in)
								: sizeof(struct sockaddr_in6), from_pos, p.proxy_timeout);
			if (!px)
				continue;
			px->target[t] = 1;
			out_fd = px->fd;
		}
		if (send_group(pl, out_fd, p.family, to, p.data, p.len) == 0) {
			from->relayed[pi]++;
			logmsg(LOG_DEBUG, "%s %s %s -> %s%s (%s)", pl->p->name, kind_name(kind), from->id, to->id,
			       ok ? "" : " (permissive)", p.desc);
		}
	}
}

static void handle_proxy(struct proxy *px)
{
	static uint8_t buf[BUF_LEN];
	struct plugin *pl = &plugins[px->plugin];
	struct mcr_pkt p;
	struct iface *from, *seeker = &ifaces[px->seeker_if];
	int ifindex, pos = 0;

	if (recv_pkt(px->fd, &p, buf, &ifindex) < 0)
		return;
	from = iface_by_index(ifindex, &pos);
	if (!from || !px->target[pos] || is_local(&p.src) || !seeker->ifindex)
		return;
	p.via_proxy = 1;
	if (pl->p->classify(&p) != MCR_ANSWER)
		return;
	/* the reply goes back unicast to the sender of the query, from the
	 * router's address on the sender's network */
	if (px->family == AF_INET)
		send_on(pl->fd4, AF_INET, seeker->ifindex, &seeker->addr4,
			(struct sockaddr *)&px->seeker, px->seeker_len, p.data, p.len);
	else
		send_on(pl->fd6, AF_INET6, seeker->ifindex, NULL,
			(struct sockaddr *)&px->seeker, px->seeker_len, p.data, p.len);
	from->relayed[px->plugin]++;
	logmsg(LOG_DEBUG, "%s reply %s -> %s (%s)", pl->p->name, from->id, seeker->id, p.desc);
}

/* ---------- main loop ---------- */

static void on_signal(int s)
{
	if (s == SIGHUP)
		sig_reload = 1;
	else if (s == SIGUSR1)
		sig_dump = 1;
	else
		sig_stop = 1;
}

static void unload(void)
{
	close_all();
	nplugins = nifaces = nrules = 0;
}

static int known_id(const char *id)
{
	for (int i = 0; i < nifaces; i++)
		if (!strcmp(ifaces[i].id, id))
			return 1;
	return 0;
}

static int load(void)
{
	permissive = 0;
	if (read_config() < 0)
		return -1;
	/* forget records about clients that are gone */
	for (int i = 0; i < MAX_RECORDS; i++)
		if (records[i].used && (!known_id(records[i].from) || !known_id(records[i].to)))
			records[i].used = 0;
	open_all();
	refresh_locals();
	scan_ifaces();
	for (int i = 0; i < nifaces; i++)
		for (int p = 0; p < nplugins; p++)
			ifaces[i].tokens[p] = ratelimit * 2;
	return 0;
}

static void usage(void)
{
	fprintf(stderr, "usage: mcast-router [-f] [-v] [-c config] [-s statedir]\n");
	exit(2);
}

int main(int argc, char **argv)
{
	time_t last_dump = 0, last_scan = 0;
	struct timespec last_tick;
	int opt;

	while ((opt = getopt(argc, argv, "fvc:s:")) != -1) {
		switch (opt) {
		case 'f': foreground = 1; break;
		case 'v': verbose = 1; break;
		case 'c': conf_path = optarg; break;
		case 's': state_dir = optarg; break;
		default: usage();
		}
	}
	openlog("mcast-router", LOG_PID, LOG_DAEMON);
	for (int i = 0; i < MAX_PROXIES; i++)
		proxies[i].fd = -1;

	struct sigaction sa = { .sa_handler = on_signal };
	sigaction(SIGHUP, &sa, NULL);
	sigaction(SIGUSR1, &sa, NULL);
	sigaction(SIGTERM, &sa, NULL);
	sigaction(SIGINT, &sa, NULL);
	signal(SIGPIPE, SIG_IGN);

	if (load() < 0)
		return 1;
	clock_gettime(CLOCK_MONOTONIC, &last_tick);

	while (!sig_stop) {
		struct pollfd pfd[MAX_PLUGINS * 2 + MAX_PROXIES];
		int what[MAX_PLUGINS * 2 + MAX_PROXIES];
		int n = 0;
		struct timespec now_ts;
		time_t now;
		double dt;

		for (int i = 0; i < nplugins; i++) {
			if (plugins[i].fd4 >= 0) {
				pfd[n] = (struct pollfd){ .fd = plugins[i].fd4, .events = POLLIN };
				what[n++] = i * 2;
			}
			if (plugins[i].fd6 >= 0) {
				pfd[n] = (struct pollfd){ .fd = plugins[i].fd6, .events = POLLIN };
				what[n++] = i * 2 + 1;
			}
		}
		for (int i = 0; i < MAX_PROXIES; i++)
			if (proxies[i].fd >= 0) {
				pfd[n] = (struct pollfd){ .fd = proxies[i].fd, .events = POLLIN };
				what[n++] = 1000 + i;
			}

		if (poll(pfd, n, 1000) > 0) {
			for (int i = 0; i < n; i++) {
				if (!(pfd[i].revents & POLLIN))
					continue;
				if (what[i] >= 1000)
					handle_proxy(&proxies[what[i] - 1000]);
				else
					handle_group(what[i] / 2, pfd[i].fd);
			}
		}

		/* housekeeping: token refill, proxy expiry, rescans, dumps */
		clock_gettime(CLOCK_MONOTONIC, &now_ts);
		dt = (now_ts.tv_sec - last_tick.tv_sec) + (now_ts.tv_nsec - last_tick.tv_nsec) / 1e9;
		last_tick = now_ts;
		for (int i = 0; i < nifaces; i++)
			for (int p = 0; p < nplugins; p++) {
				ifaces[i].tokens[p] += dt * ratelimit;
				if (ifaces[i].tokens[p] > ratelimit * 2)
					ifaces[i].tokens[p] = ratelimit * 2;
			}
		now = time(NULL);
		for (int i = 0; i < MAX_PROXIES; i++)
			if (proxies[i].fd >= 0 && proxies[i].expires < now)
				close_proxy(&proxies[i]);
		if (now - last_scan >= RESCAN_INTERVAL) {
			refresh_locals();
			scan_ifaces();
			last_scan = now;
		}
		if (sig_dump || now - last_dump >= DUMP_INTERVAL) {
			dump();
			sig_dump = 0;
			last_dump = now;
		}
		if (sig_reload) {
			sig_reload = 0;
			dump();
			unload();
			if (load() < 0)
				logmsg(LOG_ERR, "reload failed; idle until the next reload");
		}
	}
	dump();
	unload();
	return 0;
}
