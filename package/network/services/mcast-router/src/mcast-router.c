extern const struct mcr_plugin mcr_mdns, mcr_ssdp;

static const struct mcr_plugin *const builtin[] = {
	&mcr_mdns,
	&mcr_ssdp,
	NULL,
};

struct plugin {
	const struct mcr_plugin *p;
	int fd4, fd6;
	struct in_addr grp4;
	struct in6_addr grp6;
	int has4, has6;
};

struct iface {
	char name[IFNAMSIZ];
	char id[ID_LEN];
	int enforce;
	int ifindex;                    /* 0: not present (yet) */
	struct in_addr addr4;
	int has4;
	int joined4[MAX_PLUGINS];       /* ifindex the group was joined on */
	int joined6[MAX_PLUGINS];
	double tokens[MAX_PLUGINS];
	unsigned long rx[MAX_PLUGINS], relayed[MAX_PLUGINS], denied[MAX_PLUGINS], limited[MAX_PLUGINS];
};

struct rule {
	char proto[16];                 /* plugin name or "*" */
	char seeker[ID_LEN];            /* "*" for 'out' rules */
	char provider[ID_LEN];
};

struct proxy {
	int fd;                         /* -1: free */
	int plugin;
	int family;
	struct sockaddr_storage seeker;
	socklen_t seeker_len;
	int seeker_if;                  /* index into ifaces */
	unsigned char target[MAX_IFACES];
	time_t expires;
	uint16_t port;
};

struct record {
	int used;
	int denied;                     /* 1: denied, 0: would be denied (permissive) */
	const struct mcr_plugin *proto;
	int kind;
	char from[ID_LEN], to[ID_LEN];
	unsigned long count;
	time_t first, last;
	char desc[MCR_DESC_LEN];
};

struct local_addr {
	int family;
	union { struct in_addr a4; struct in6_addr a6; } u;
};

